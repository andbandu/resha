function makeStock(index: number): ProductSizeStock[] {
  return [
    { size: "XS", inStock: index % 9 !== 0, stockCount: index % 9 === 0 ? 0 : 4 + (index % 4) },
    { size: "S", inStock: true, stockCount: 8 + (index % 7) },
    { size: "M", inStock: true, stockCount: 10 + (index % 6) },
    { size: "L", inStock: true, stockCount: 6 + (index % 5) },
    { size: "XL", inStock: index % 7 !== 0, stockCount: index % 7 === 0 ? 0 : 3 + (index % 4) },
  ];
}

function makeReviews(seed: ProductSeed, index: number): ProductReview[] {
  const r1 = REVIEWER_POOL[index % REVIEWER_POOL.length];
  const r2 = REVIEWER_POOL[(index + 2) % REVIEWER_POOL.length];
  return [
    {
      id: `rev-${index + 1}-1`,
      author: r1.author,
      location: r1.location,
      rating: 5,
      date: "November 2026",
      sizePurchased: r1.size,
      fitFeedback: "True to Size",
      comment: `Love how refined the ${seed.name} feels in person. The ${seed.fabricFamily.toLowerCase()} drapes cleanly without losing structure.`,
    },
    {
      id: `rev-${index + 1}-2`,
      author: r2.author,
      location: r2.location,
      rating: index % 4 === 0 ? 4 : 5,
      date: "October 2026",
      sizePurchased: r2.size,
      fitFeedback: "True to Size",
      comment: `Effortless everyday styling in ${seed.colorName}. Holds its finish beautifully from daytime errands to dinner.`,
    },
  ];
}

function buildProduct(seed: ProductSeed, index: number): Product {
  const images = Array.from({ length: seed.imageCount }, (_, idx) => {
    const imageNum = idx + 1;
    return {
      src: getS3ImageUrl(`${seed.prefix} image ${imageNum}.webp`),
      alt: `${seed.name} in ${seed.colorName} — view ${imageNum}`,
      caption: IMAGE_CAPTIONS[idx] ?? `Detail look ${imageNum}`,
    };
  });

  const padded = String(index + 1).padStart(3, "0");
  const skuCode = `RSH-${SKU_PREFIX_BY_CATEGORY[seed.category]}-${101 + index}`;

  return {
    id: `rsh-${padded}`,
    slug: seed.slug,
    sku: skuCode,
    name: seed.name,
    subtitle: seed.subtitle,
    category: seed.category,
    collection: seed.collection,
    price: seed.price,
    compareAtPrice: seed.compareAtPrice,
    badge: seed.badge,
    fabric: seed.fabric,
    fabricFamily: seed.fabricFamily,
    gsm: seed.gsm,
    origin: "Resha Contemporary Studio",
    description: seed.description,
    details: seed.details,
    fitNotes: seed.fitNotes,
    careInstructions: CARE_BY_FAMILY[seed.fabricFamily],
    colors: [
      {
        name: seed.colorName,
        hex: seed.colorHex,
        image: images[0].src,
      },
    ],
    sizes: makeStock(index),
    images,
    rating: Number((4.7 + ((index % 3) * 0.1)).toFixed(1)),
    reviewCount: 12 + (index % 23),
    reviews: makeReviews(seed, index),
    featured: seed.featured,
    isNew: seed.isNew,
  };
}

